/** Display name for a VS Code languageId; unknown ids are capitalized ("foo-bar" -> "Foo-bar"). */
export function languageName(languageId: string): string | undefined {
  if (!languageId) return undefined;
  const known = LANGUAGE_NAMES[languageId];
  if (known) return known;
  return languageId.charAt(0).toUpperCase() + languageId.slice(1);
}
